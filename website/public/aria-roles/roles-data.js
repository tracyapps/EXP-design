export const CONFUSED_PAIRS = (() => {
  const seen = new Set();
  const pairs = [];
  for (const r of ROLES) {
    for (const c of (r.confused || [])) {
      const key = [r.id, c.id].sort().join('|');
      if (seen.has(key)) continue;
      seen.add(key);
      const other = ROLES.find((x) => x.id === c.id);
      if (other) pairs.push({ a: r.id, b: c.id, why: c.why });
    }
  }
  return pairs;
})();

export function findRole(id) { return ROLES.find((r) => r.id === id) || null; }
export function docLinks(id) { return docs(id); }
export function searchRoles(query, limit = 8) {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  const scored = ROLES.map((r) => {
    let score = 0;
    if (r.id === q) score = 100;
    else if (r.name.toLowerCase().startsWith(q)) score = 90;
    else if (r.name.toLowerCase().includes(q)) score = 70;
    else if ((r.tags || []).some((t) => t.toLowerCase().includes(q))) score = 50;
    else if (r.sum.toLowerCase().includes(q)) score = 20;
    return { r, score };
  }).filter((x) => x.score > 0).sort((a, b) => b.score - a.score);
  return scored.slice(0, limit).map((x) => x.r);
}
